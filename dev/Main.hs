-- | Development checks for the Ironframe repository. Run from the repository root:
--
--   ironframe-dev generate            write src/Ironframe/Embedded.hs from the schemas
--   ironframe-dev generate --check    fail when src/Ironframe/Embedded.hs is stale
--   ironframe-dev integrity           npm/build.json matches sources and artifacts,
--                                     and staged npm copies match their sources
--   ironframe-dev integrity --record  rewrite npm/build.json (tools/wasm.sh)
--
-- Mirrors LawSpec's dev/Main.hs. ref:DEC-haskell-wasm-core
module Main (main) where

import Control.Monad (forM, forM_, unless)
import qualified Crypto.Hash.SHA256 as SHA256
import qualified Data.ByteString as B
import Data.Char (intToDigit)
import Data.List (intercalate, isPrefixOf, isSuffixOf, sort)
import qualified Data.Text as T
import qualified Data.Text.Encoding as TE
import System.Directory (doesDirectoryExist, doesFileExist, listDirectory)
import System.Environment (getArgs)
import System.Exit (die)

main :: IO ()
main = getArgs >>= \case
  ["generate"] -> generate False
  ["generate", "--check"] -> generate True
  ["integrity"] -> integrity False
  ["integrity", "--record"] -> integrity True
  _ -> die "usage: ironframe-dev generate [--check] | integrity [--record]"

-- | The embedded module's path.
embeddedPath :: FilePath
embeddedPath = "src/Ironframe/Embedded.hs"

-- | Each embedded value and the file whose exact text it holds.
embedded :: [(String, FilePath)]
embedded =
  [ ("manifestSchema", "schema/ironframe-v1.schema.json")
  , ("attestationSchema", "schema/attestation-v1.schema.json")
  , ("contractDecoratorSchema", "schema/calm/ironframe-contract.decorator.schema.json")
  , ("bindingDecoratorSchema", "schema/calm/ironframe-binding.decorator.schema.json")
  , ("environmentDecoratorSchema", "schema/calm/ironframe-environment.decorator.schema.json")
  , ("calmCore", "schema/calm/1.2/core.json")
  , ("calmControl", "schema/calm/1.2/control.json")
  , ("calmFlow", "schema/calm/1.2/flow.json")
  , ("calmInterface", "schema/calm/1.2/interface.json")
  , ("calmDecorators", "schema/calm/1.2/decorators.json")
  ]

-- | Writes the embedded module, or with @check@ fails when it differs.
generate :: Bool -> IO ()
generate check = do
  values <- forM embedded $ \(name, file) -> do
    bytes <- B.readFile file
    text <- either (const (die (file ++ " is not UTF-8"))) pure (TE.decodeUtf8' bytes)
    pure (name, file, T.unpack text)
  let rendered = TE.encodeUtf8 (T.pack (renderEmbedded values))
  if check
    then do
      exists <- doesFileExist embeddedPath
      current <- if exists then B.readFile embeddedPath else pure B.empty
      unless (current == rendered) (die (embeddedPath ++ " is stale; run ironframe-dev generate"))
      putStrLn (embeddedPath ++ " is current.")
    else B.writeFile embeddedPath rendered

-- | The module text. Each value is one literal with a string gap after each
-- line of its file, so the source stays readable and decodes to exactly its
-- text.
renderEmbedded :: [(String, FilePath, String)] -> String
renderEmbedded values = unlines $
  [ "-- | Generated by ironframe-dev generate. Do not edit."
  , "-- The schemas the core serves and validates against, as their exact text."
  , "module Ironframe.Embedded"
  , "  ( " ++ intercalate "\n  , " [name | (name, _, _) <- values]
  , "  ) where"
  , ""
  , "import Data.Text (Text)"
  ]
    ++ concat
      [ ["", "-- | " ++ file ++ ".", name ++ " :: Text", name ++ " =", "  \"" ++ literal text ++ "\""]
      | (name, file, text) <- values
      ]
  where
    -- Every piece but the last ends in a newline escape, so a gap never
    -- follows a numeric escape that the next piece's digits could extend.
    literal text = intercalate "\\\n  \\" (map (unquote . show) (pieces text))
    unquote = reverse . drop 1 . reverse . drop 1
    pieces "" = []
    pieces s = case break (== '\n') s of
      (line, '\n' : rest) -> (line ++ "\n") : pieces rest
      (line, _) -> [line]

-- | Every core source and generated npm artifact is fingerprinted, so a
-- published package can never pair a WASM build with different sources.
integrity :: Bool -> IO ()
integrity record = do
  haskell <- walk (".hs" `isSuffixOf`) "src"
  wasmApp <- walk (".hs" `isSuffixOf`) "wasm/app"
  let sources = sort (haskell ++ wasmApp ++
        [ "package.yaml", "ironframe.cabal", "stack.yaml", "stack.yaml.lock"
        , "wasm/cabal.project", "wasm/cabal.project.freeze", "wasm/ironframe-wasm.cabal" ])
      artifacts = ["npm/core.wasm", "npm/core_jsffi.js"]
  digests <- forM (sources ++ artifacts) $ \file -> (,) file . hex . SHA256.hash <$> B.readFile file
  if record
    then writeFile "npm/build.json" (render sources digests)
    else do
      stagedCopies
      recorded <- readFile "npm/build.json"
      unless (recorded == render sources digests) $ do
        let stale = [file | (file, digest) <- digests, not (quoted digest `isInfixOf'` recorded
                      && quoted file `isInfixOf'` recorded)]
        die (case stale of
          file : _ -> "Stale build artifact/source: " ++ file ++ "; run tools/wasm.sh"
          [] -> "Core source set changed; run tools/wasm.sh")
      putStrLn "WASM and core source fingerprints match."
  where
    quoted s = "\"" ++ s ++ "\""
    isInfixOf' needle haystack = any (needle `isPrefixOf`) (tails' haystack)
    tails' [] = [[]]
    tails' s@(_ : rest) = s : tails' rest

-- | tools/wasm.sh stages the license into npm/; it stays committed, so it must
-- be byte-identical to its source. README.md and CHANGELOG.md are copied by
-- npm's prepack instead and not committed.
stagedCopies :: IO ()
stagedCopies =
  forM_ [("LICENSE", "npm/LICENSE")] $ \(source, copy) -> do
    exists <- doesFileExist copy
    same <- if exists then (==) <$> B.readFile source <*> B.readFile copy else pure False
    unless same (die ("Stale npm copy: " ++ copy ++ " differs from " ++ source ++ "; run tools/wasm.sh"))

-- | Directory entries are visited in sorted order; hidden and dunder entries
-- are build output, not sources.
walk :: (FilePath -> Bool) -> FilePath -> IO [FilePath]
walk select dir = do
  entries <- sort . filter keep <$> listDirectory dir
  concat <$> forM entries (\entry -> do
    let path = dir ++ "/" ++ entry
    isDirectory <- doesDirectoryExist path
    if isDirectory then walk select path
    else pure [path | select path])
  where keep name = not ("." `isPrefixOf` name || "__" `isPrefixOf` name)

hex :: B.ByteString -> String
hex = concatMap (\w -> [intToDigit (fromIntegral w `div` 16), intToDigit (fromIntegral w `mod` 16)]) . B.unpack

-- | The layout matches JSON.stringify(record, null, 2), as LawSpec's does.
render :: [FilePath] -> [(FilePath, String)] -> String
render sources digests = unlines
  [ "{"
  , "  \"version\": 1,"
  , "  \"coreSources\": ["
  , intercalate ",\n" ["    " ++ json s | s <- sources]
  , "  ],"
  , "  \"digests\": {"
  , intercalate ",\n" ["    " ++ json file ++ ": " ++ json digest | (file, digest) <- digests]
  , "  }"
  , "}" ]
  where json s = "\"" ++ concatMap escape s ++ "\""
        escape '"' = "\\\""
        escape '\\' = "\\\\"
        escape c = [c]
