-- | The compose file of a podman environment: one service per dependency that
-- runs from an image, labelled with its project, environment and dependency so
-- @status@ and @down@ find it, and the configuration service when asked for.
-- It is generated whole on every @up@. ref:DEC-podman-compose
module Ironframe.Compose
  ( labelProject
  , labelEnvironment
  , labelDependency
  , labelKind
  , configServiceName
  , configServiceSettingsPath
  , composeFile
  ) where

import qualified Data.Map.Strict as Map
import Data.Text (Text)
import qualified Data.Text as T
import Ironframe.Json
import Ironframe.Manifest (ConfigService (..))
import Ironframe.Settings
import Ironframe.Yaml (encodeYaml)

labelProject, labelEnvironment, labelDependency, labelKind :: Text
labelProject = "io.ironframe.project"
labelEnvironment = "io.ironframe.environment"
labelDependency = "io.ironframe.dependency"
labelKind = "io.ironframe.kind"

-- | The compose service name of the configuration service.
configServiceName :: Text
configServiceName = "ironframe-config-service"

-- | Where the configuration service reads its settings document.
configServiceSettingsPath :: Text
configServiceSettingsPath = "/etc/ironframe/settings.json"

-- | The compose file for a resolved podman environment, with the
-- configuration service and the settings document it serves when given.
composeFile :: ResolvedEnvironment -> Maybe (ConfigService, Text) -> Text
composeFile environment configService =
  "# Generated by ironframe from the manifest for environment " <> reEnvironment environment <> " of " <> reProject environment
    <> "; edits are overwritten by `ironframe up`.\n"
    <> encodeYaml (Object ["name" .= String stack, "services" .= Object (Map.toAscList services)])
  where
    stack = stackName environment
    tshow = T.pack . show
    labels dependency kind =
      Object
        [ labelDependency .= String dependency
        , labelEnvironment .= String (reEnvironment environment)
        , labelKind .= String kind
        , labelProject .= String (reProject environment)
        ]
    service image name ports env volumes ls =
      Object $
        ["image" .= String image, "container_name" .= String name]
          ++ ["ports" .= Array (map String ports) | not (null ports)]
          ++ ["environment" .= fromTextMap env | not (Map.null env)]
          ++ ["volumes" .= Array (map String volumes) | not (null volumes)]
          ++ ["labels" .= ls]
    dependencyServices =
      Map.fromList
        [ ( rdName d
          , service
              image
              (stack <> "-" <> rdName d)
              ([tshow p <> ":" <> tshow p | p <- rdPorts d] ++ [tshow h <> ":" <> tshow c | Just (h, c) <- [rdAdminPort d]])
              (rdContainerEnv d)
              []
              (labels (rdName d) (kindWord (rdKind d)))
          )
        | d <- reDependencies environment
        , Just image <- [rdImage d]
        ]
    services = case configService of
      Nothing -> dependencyServices
      Just (cs, settings) ->
        Map.insert
          configServiceName
          ( service
              (qualifyImage (configServiceImage cs))
              (stack <> "-config-service")
              [tshow (configServicePort cs) <> ":" <> tshow (configServicePort cs)]
              (Map.fromList [("IRONFRAME_SETTINGS", configServiceSettingsPath), ("IRONFRAME_LISTEN", "0.0.0.0:" <> tshow (configServicePort cs))])
              [settings <> ":" <> configServiceSettingsPath <> ":ro,Z"]
              (labels configServiceName "config-service")
          )
          dependencyServices
