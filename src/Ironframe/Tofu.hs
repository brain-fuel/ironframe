-- | The released modules, used when an environment names no @cloud.modules@.
releasedModules :: Text
releasedModules = "git::https://github.com/brain-fuel/ironframe.git//modules?ref=v0.1.0"

endpointsOutput :: Text
endpointsOutput = "endpoints"

data TofuError
  = NotInstalled
  | NotCloud Text
  | Failed Text Text Text
  | Output Text
  | Io Text Text
  deriving (Show, Eq)

renderTofuError :: TofuError -> Text
renderTofuError = \case
  NotInstalled ->
    "a cloud environment needs OpenTofu: set IRONFRAME_TOFU, or install it (`brew install opentofu`, or https://opentofu.org/docs/intro/install/); terraform on PATH also works"
  NotCloud name ->
    "environment " <> debugStr name <> " runs on podman; `plan` is for cloud environments, and `ironframe up " <> name <> "` runs it locally"
  Failed tool command reason -> "`" <> tool <> " " <> command <> "` failed: " <> reason
  Output reason -> "cannot read the endpoints output: " <> reason
  Io program reason -> "cannot run " <> program <> ": " <> reason

-- | The source of a module under a base: a local path made absolute against
-- the manifest's directory, or a remote source with the module put before
-- its query.
moduleSource :: Text -> Text -> Text -> Text
moduleSource base m manifestDir
  | not remote = Path.join (if Path.isAbsolute base then base else Path.join manifestDir base) m
  | otherwise = case T.breakOn "?" base of
      (source, query) | not (T.null query) -> T.dropWhileEnd (== '/') source <> "/" <> m <> query
      _ -> T.dropWhileEnd (== '/') base <> "/" <> m
  where
    remote = "::" `T.isInfixOf` base || "://" `T.isInfixOf` base || "github.com/" `T.isPrefixOf` base

-- | The resource name a twin is deployed under.
deploymentName :: Text -> Text -> Text -> Text
deploymentName project environment dependency = T.replace "_" "-" (project <> "-" <> environment <> "-" <> dependency)

-- | The root module of a cloud environment, as OpenTofu's JSON syntax.
rootModule :: Manifest -> Text -> Text -> Either TofuError Value
rootModule manifest name manifestDir = do
  environment <- either (Left . Output . renderManifestError) Right (environmentOf manifest name)
  let runtime = envRuntime environment
  if not (runtimeIsCloud runtime) then Left (NotCloud name) else Right ()
  let cloud = fromMaybe (Cloud Nothing Map.empty) (envCloud environment)
      base = fromMaybe releasedModules (cloudModules cloud)
  instances <- sequence [instanceOf runtime cloud base dependency twin | (dependency, BindTwin twin) <- Map.toAscList (envDependencies environment)]
  let modules = [(k, v) | (k, v, _) <- instances]
      endpoints = [(d, e) | (_, _, (d, e)) <- instances]
      (providerName, providerConfig) = provider runtime cloud
      (requiredName, required') = requiredProvider runtime
      root =
        Object
          [ "//" .= String ("Generated by ironframe for environment " <> name <> " of " <> manifestProject manifest <> "; edits are overwritten.")
          , "terraform" .= Object ["required_version" .= String ">= 1.6.0", "required_providers" .= Object [requiredName .= required']]
          , "provider" .= Object [providerName .= Array [providerConfig]]
          , "output" .= Object [endpointsOutput .= Object ["description" .= String "Each twin's endpoint, by dependency.", "value" .= Object endpoints]]
          ]
  pure (if null modules then root else insert "module" (Object modules) root)
  where
    instanceOf runtime cloud base dependency twin = do
      m <- maybe (Left (NotCloud name)) Right (runtimeModule runtime (twinProtocolOrDefault twin))
      let env = Map.insert twinConfigVariable (encode (twinConfigJson twin)) (twinEnv twin)
          inputs =
            [ "source" .= String (moduleSource base m manifestDir)
            , "name" .= String (deploymentName (manifestProject manifest) name dependency)
            , "image" .= String (qualifyImage (twinImageRef twin))
            , "ports" .= Array [Number (I p) | p <- twinPorts twin]
            , "environment" .= fromTextMap env
            ]
              ++ maybe [] (\v -> ["advertise_variable" .= String v]) (twinAdvertiseVariable twin)
              ++ [(i, v) | i <- inputsOfModule m, Just v <- [Map.lookup i (cloudInputs cloud)]]
          k = "twin_" <> T.replace "-" "_" dependency
      pure (k, Object inputs, (dependency, String ("${module." <> k <> ".endpoint}")))

provider :: Runtime -> Cloud -> (Text, Value)
provider runtime cloud =
  let config = [(i, v) | i <- providerInputs runtime, Just v <- [Map.lookup i (cloudInputs cloud)]]
   in case runtime of
        Aws -> ("aws", Object config)
        Gcp -> ("google", Object config)
        Azure -> ("azurerm", Object (config ++ ["features" .= Object []]))
        Podman -> ("podman", Object config)

requiredProvider :: Runtime -> (Text, Value)
requiredProvider = \case
  Aws -> ("aws", Object ["source" .= String "hashicorp/aws", "version" .= String ">= 6.0, < 7.0"])
  Gcp -> ("google", Object ["source" .= String "hashicorp/google", "version" .= String ">= 6.0, < 8.0"])
  Azure -> ("azurerm", Object ["source" .= String "hashicorp/azurerm", "version" .= String ">= 4.0, < 5.0"])
  Podman -> ("podman", Object [])

-- | OpenTofu, or Terraform, found and ready to run in one root directory.
data Tofu = Tofu {tofuProgram :: Text, tofuRoot :: Text}

-- | Finds @IRONFRAME_TOFU@, then @tofu@, then @terraform@ on PATH.
locateTofu :: Text -> Eff (Either TofuError Tofu)
locateTofu root = do
  found <- locate "IRONFRAME_TOFU" ["tofu", "terraform"] ["/opt/homebrew/bin/tofu"]
  pure (maybe (Left NotInstalled) (\p -> Right (Tofu p root)) found)

runTofu :: Tofu -> [Text] -> Bool -> Eff (Either TofuError ProcessOutput)
runTofu t args stream = do
  result <- runProcess (tofuProgram t) (("-chdir=" <> tofuRoot t) : args) stream
  pure $ case result of
    Left e -> Left (Io (tofuProgram t) (ioMessage e))
    Right out
      | procSuccess out -> Right out
      | otherwise ->
          Left
            ( Failed
                (fromMaybe "" (Path.fileName (tofuProgram t)))
                (T.unwords args)
                (if stream then "see the output above" else lastLine (procStderr out))
            )

tofuInit, tofuPlan, tofuApply, tofuDestroy :: Tofu -> Eff (Either TofuError ())
tofuInit t = fmap (() <$) (runTofu t ["init", "-input=false"] True)
tofuPlan t = fmap (() <$) (runTofu t ["plan", "-input=false"] True)
tofuApply t = fmap (() <$) (runTofu t ["apply", "-input=false", "-auto-approve"] True)
tofuDestroy t = fmap (() <$) (runTofu t ["destroy", "-input=false", "-auto-approve"] True)

-- | The endpoint of each deployed twin, from the endpoints output.
tofuEndpoints :: Tofu -> Eff (Either TofuError (Map Text Text))
tofuEndpoints t = do
  result <- runTofu t ["output", "-json", endpointsOutput] False
  pure $ do
    out <- result
    either (Left . Output) Right (fromStr ExpectMap (textMap string) (procStdout out))
