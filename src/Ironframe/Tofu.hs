-- | A cloud environment's OpenTofu root: generated as JSON from the manifest,
-- one module instance per twin, the provider configured from the cloud
-- inputs, and one output mapping each twin to its endpoint. The driver runs
-- OpenTofu, or Terraform, through the host. ref:DEC-opentofu
