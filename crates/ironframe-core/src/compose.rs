//! The compose file of a podman environment: one service per dependency that runs from an image,
//! each labelled with its project, environment and dependency so `status` and `down` find it, and
//! the configuration service when the environment asks for one. The file is generated whole on
//! every `up`, never edited, so it cannot drift from the manifest. ref:DEC-podman-compose

use crate::manifest::ConfigService;
use crate::settings::{ResolvedEnvironment, qualify_image};
use serde::Serialize;
use std::collections::BTreeMap;
use std::path::Path;

/// The label naming the project a container belongs to. ref:DEC-podman-compose
pub const LABEL_PROJECT: &str = "io.ironframe.project";
/// The label naming the environment a container belongs to. ref:DEC-podman-compose
pub const LABEL_ENVIRONMENT: &str = "io.ironframe.environment";
/// The label naming the dependency a container serves. ref:DEC-podman-compose
pub const LABEL_DEPENDENCY: &str = "io.ironframe.dependency";
/// The label naming whether the container is the real dependency or a twin. ref:DEC-podman-compose
pub const LABEL_KIND: &str = "io.ironframe.kind";

/// The compose service name of the configuration service. ref:DEC-config-service
pub const CONFIG_SERVICE: &str = "ironframe-config-service";

/// Where the configuration service reads the settings document inside its container.
/// ref:DEC-config-service
pub const CONFIG_SERVICE_SETTINGS_PATH: &str = "/etc/ironframe/settings.json";

#[derive(Serialize)]
struct ComposeFile {
    name: String,
    services: BTreeMap<String, Service>,
}

#[derive(Serialize)]
struct Service {
    image: String,
    container_name: String,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    ports: Vec<String>,
    #[serde(skip_serializing_if = "BTreeMap::is_empty")]
    environment: BTreeMap<String, String>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    volumes: Vec<String>,
    labels: BTreeMap<String, String>,
}

/// The compose file for a resolved podman environment. `config_service` names the service to add
/// and the settings document on this machine it serves. Ports keep their numbers on the host, so
/// the endpoint a twin is reached at is the one the application is told; a twin's control plane is
/// published on the port its `admin` names. ref:DEC-podman-compose ref:DEC-twin-control-plane
pub fn compose_file(environment: &ResolvedEnvironment, config_service: Option<(&ConfigService, &Path)>) -> String {
    let stack = environment.stack_name();
    let labels = |dependency: &str, kind: &str| {
        BTreeMap::from([
            (LABEL_PROJECT.to_string(), environment.project.clone()),
            (LABEL_ENVIRONMENT.to_string(), environment.environment.clone()),
            (LABEL_DEPENDENCY.to_string(), dependency.to_string()),
            (LABEL_KIND.to_string(), kind.to_string()),
        ])
    };
    let mut services = BTreeMap::new();
    for dependency in &environment.dependencies {
        let Some(image) = &dependency.image else { continue };
        services.insert(
            dependency.name.clone(),
            Service {
                image: image.clone(),
                container_name: format!("{stack}-{}", dependency.name),
                ports: dependency
                    .ports
                    .iter()
                    .map(|p| format!("{p}:{p}"))
                    .chain(dependency.admin_port.map(|(host, container)| format!("{host}:{container}")))
                    .collect(),
                environment: dependency.container_env.clone(),
                volumes: Vec::new(),
                labels: labels(&dependency.name, dependency.kind.as_str()),
            },
        );
    }
    if let Some((service, settings)) = config_service {
        services.insert(
            CONFIG_SERVICE.to_string(),
            Service {
                image: qualify_image(&service.image),
                container_name: format!("{stack}-config-service"),
                ports: vec![format!("{}:{}", service.port, service.port)],
                environment: BTreeMap::from([
                    ("IRONFRAME_SETTINGS".to_string(), CONFIG_SERVICE_SETTINGS_PATH.to_string()),
                    ("IRONFRAME_LISTEN".to_string(), format!("0.0.0.0:{}", service.port)),
                ]),
                volumes: vec![format!("{}:{CONFIG_SERVICE_SETTINGS_PATH}:ro,Z", settings.display())],
                labels: labels(CONFIG_SERVICE, "config-service"),
            },
        );
    }
    let file = ComposeFile { name: stack, services };
    let mut text = format!(
        "# Generated by ironframe from the manifest for environment {} of {}; edits are overwritten by `ironframe up`.\n",
        environment.environment, environment.project
    );
    text.push_str(&serde_yaml::to_string(&file).expect("a compose file serialises"));
    text
}
