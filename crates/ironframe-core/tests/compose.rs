//! The compose file of a podman environment is generated whole from the resolved environment:
//! one labelled service per container, ports kept, the twin's configuration passed in, and the
//! configuration service when asked for. ref:DEC-podman-compose

mod common;

use ironframe_core::compose::compose_file;
use ironframe_core::manifest::{ConfigService, Manifest};
use ironframe_core::settings::resolve;
use std::collections::BTreeMap;
use std::path::Path;

fn local() -> ironframe_core::settings::ResolvedEnvironment {
    resolve(&common::manifest(), "local", &BTreeMap::new()).unwrap()
}

/// ref:REQ-compose-generation
#[test]
fn each_container_is_a_labelled_service_with_its_ports_and_environment() {
    let text = compose_file(&local(), None);
    let compose: serde_yaml::Value = serde_yaml::from_str(&text).unwrap();
    assert_eq!(compose["name"], "ironframe-shop-local");
    let kafka = &compose["services"]["kafka"];
    assert_eq!(kafka["image"], "docker.io/lawtwin/kafka:0.1.0");
    assert_eq!(kafka["container_name"], "ironframe-shop-local-kafka");
    assert_eq!(kafka["ports"], serde_yaml::to_value(["9092:9092", "9644:9644"]).unwrap());
    assert_eq!(kafka["environment"]["TWIN_CONFIG"], r#"{"seed":42}"#);
    assert_eq!(kafka["labels"]["io.ironframe.project"], "shop");
    assert_eq!(kafka["labels"]["io.ironframe.environment"], "local");
    assert_eq!(kafka["labels"]["io.ironframe.dependency"], "kafka");
    assert_eq!(kafka["labels"]["io.ironframe.kind"], "twin");
    assert_eq!(compose["services"]["payments"]["image"], "ghcr.io/example/payments-twin:2.0.0");
}

/// ref:REQ-compose-generation
#[test]
fn a_hosted_real_dependency_gets_no_service() {
    let manifest = Manifest::parse(
        "version: 1\nproject: shop\ndependencies:\n  kafka:\n    settings: {K: '${endpoint}'}\n  db:\n    settings: {D: '${endpoint}'}\nenvironments:\n  local:\n    runtime: podman\n    dependencies:\n      kafka: {real: {endpoint: 'localhost:9092', image: 'apache/kafka:4.1.0', ports: [9092]}}\n      db: {real: {endpoint: 'db.example.com:5432'}}\n",
    )
    .unwrap();
    let text = compose_file(&resolve(&manifest, "local", &BTreeMap::new()).unwrap(), None);
    let compose: serde_yaml::Value = serde_yaml::from_str(&text).unwrap();
    let services = compose["services"].as_mapping().unwrap();
    assert_eq!(services.len(), 1);
    assert_eq!(compose["services"]["kafka"]["image"], "docker.io/apache/kafka:4.1.0");
    assert_eq!(compose["services"]["kafka"]["labels"]["io.ironframe.kind"], "real");
}

/// ref:REQ-compose-generation
#[test]
fn the_configuration_service_mounts_the_settings_document_read_only() {
    let service = ConfigService { image: "localhost/ironframe-config-service:0.1.0".into(), port: 8700 };
    let text = compose_file(&local(), Some((&service, Path::new("/work/.ironframe/local/settings.json"))));
    let compose: serde_yaml::Value = serde_yaml::from_str(&text).unwrap();
    let config = &compose["services"]["ironframe-config-service"];
    assert_eq!(config["ports"][0], "8700:8700");
    assert_eq!(config["volumes"][0], "/work/.ironframe/local/settings.json:/etc/ironframe/settings.json:ro,Z");
    assert_eq!(config["environment"]["IRONFRAME_LISTEN"], "0.0.0.0:8700");
}

/// ref:REQ-compose-generation
#[test]
fn the_same_manifest_always_gives_the_same_file() {
    let first = compose_file(&local(), None);
    assert_eq!(first, compose_file(&local(), None));
    assert!(first.starts_with("# Generated by ironframe"));
}
